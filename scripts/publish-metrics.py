"""Publish a validated lowlighter/metrics SVG; preserve the previous render on failure."""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

BEGIN = "<!-- METRICS:START -->"
END = "<!-- METRICS:END -->"
README = Path("README.md")
DEST = Path("assets/metrics/github-metrics.svg")
BLOCK = """
<p align="center">
  <img src="./assets/metrics/github-metrics.svg" width="100%" alt="GitHub metrics: contribution calendar, repository statistics, language activity and available coding habits" />
</p>

<sub>Public-data coverage · Generated by <a href="https://github.com/lowlighter/metrics">lowlighter/metrics</a> · <a href="./.github/workflows/metrics.yml">Workflow</a></sub>
"""

def main():
    candidate = Path(sys.argv[1])
    data = candidate.read_bytes()
    if not 3000 <= len(data) <= 5_000_000:
        raise ValueError("Unexpected Metrics SVG size")
    root = ET.fromstring(data)
    if root.tag.rsplit("}", 1)[-1] != "svg":
        raise ValueError("Not an SVG")
    text = " ".join(" ".join(root.itertext()).split()).lower()
    # Classic base.header renders user.name || user.login, not always the login.
    def local_name(element):
        return element.tag.rsplit("}", 1)[-1]

    headers = [
        " ".join(" ".join(el.itertext()).split())
        for el in root.iter() if local_name(el) == "h1"
    ]
    if not any(header in {"渡", "shengruduzhou"} for header in headers):
        raise ValueError(f"Unexpected Metrics account header: {headers!r}")
    headings = {
        " ".join(" ".join(el.itertext()).split()).lower()
        for el in root.iter() if local_name(el) in {"h2", "h3"}
    }
    if not {"contributions calendar", "most used languages"} <= headings:
        raise ValueError(f"Missing required Metrics sections: {sorted(headings)!r}")
    if any("error" in el.get("class", "").split() for el in root.iter()
           if local_name(el) in {"div", "section", "span"}):
        raise ValueError("Metrics contains a plugin error block")
    if re.search(r"rate limit exceeded|bad credentials|plugin error|unexpected error|not enough scopes|user not found|service unavailable|unable to fetch|error occurred", text):
        raise ValueError("Metrics render contains an API error")
    for el in root.iter():
        if el.tag.rsplit("}", 1)[-1].lower() == "script":
            raise ValueError("Unexpected executable SVG content")
        if any(key.rsplit("}", 1)[-1].lower().startswith("on") for key in el.attrib):
            raise ValueError("Unexpected SVG event handler")
    readme = README.read_text(encoding="utf-8")
    if readme.count(BEGIN) != 1 or readme.count(END) != 1:
        raise ValueError("Metrics markers missing or duplicated")
    start = readme.index(BEGIN) + len(BEGIN)
    end = readme.index(END, start)
    new_readme = readme[:start] + "\n" + BLOCK.strip() + "\n" + readme[end:]
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_bytes(data)
    README.write_text(new_readme, encoding="utf-8")

if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, ET.ParseError) as error:
        print(f"::warning::Metrics not published: {error}")
        sys.exit(1)
